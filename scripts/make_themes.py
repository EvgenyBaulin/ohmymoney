#!/usr/bin/env python3
"""Writes the Swift data of the colour themes from the themes JSON.

The JSON (30 themes, light and dark, 54 tokens each, colours as `#RRGGBB` or `#RRGGBBAA`)
is kept outside the repository; the Swift written from it is committed. A token such as
`account/1/start` becomes the property `account1Start`.

Usage:

    make_themes.py themes.json [Themes-folder]   # writes the two generated files
    make_themes.py --self-test                   # checks naming, parsing and determinism

Two files are written: `ThemeCatalog.generated.swift` (plain data, no UI framework) and
`ThemeColors.generated.swift` (the same tokens as SwiftUI colours). The default folder is
`Apps/macOS/Shared/DesignSystem/Themes`.
"""
import json
import os
import re
import sys

DEFAULT_DIR = os.path.join("Apps", "macOS", "Shared", "DesignSystem", "Themes")
HEX = re.compile(r"^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$")
HEADER = "// Generated by scripts/make_themes.py from the themes JSON. Do not edit by hand.\n"


def camel(token):
    """`account/1/start` -> `account1Start`, `content/on-accent` -> `contentOnAccent`."""
    words = [word for part in token.split("/") for word in part.split("-")]
    return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:])


def rgba(value):
    match = HEX.match(value)
    if not match:
        raise ValueError(f"not a colour: {value!r}")
    return "0x" + (match.group(1) + (match.group(2) or "ff")).upper()


def validate(data):
    tokens = data["tokens"]
    if len(set(camel(token) for token in tokens)) != len(tokens):
        raise ValueError("token names collide in code")
    ids = [theme["id"] for theme in data["themes"]]
    if ids != ["%02d" % number for number in range(1, len(ids) + 1)]:
        raise ValueError(f"theme ids are not 01...N in order: {ids}")
    for theme in data["themes"]:
        for scheme in ("light", "dark"):
            palette = theme[scheme]
            if set(palette) != set(tokens):
                raise ValueError(f"theme {theme['id']} {scheme}: tokens differ from the list")
            for token in tokens:
                rgba(palette[token])


def catalog_source(data):
    tokens = data["tokens"]
    names = [camel(token) for token in tokens]
    out = [HEADER, "// swift-format-ignore-file\n\n"]
    out.append("/// The theme numbers, as the themes JSON names them.\n")
    out.append("public enum ThemeID: String, CaseIterable, Sendable {\n")
    for theme in data["themes"]:
        out.append(f'  case theme{theme["id"]} = "{theme["id"]}"\n')
    out.append("\n  /// The key of the theme's name in the `Themes` String Catalog.\n")
    out.append('  public var nameKey: String { "theme.name.\\(rawValue)" }\n}\n\n')
    out.append("/// Every colour of one theme in one scheme.\n")
    out.append("public struct ThemePalette: Equatable, Sendable {\n")
    for name in names:
        out.append(f"  public let {name}: ThemeColor\n")
    out.append("\n  /// The tokens in the order of the themes JSON, under their JSON names.\n")
    out.append("  public var all: [(token: String, color: ThemeColor)] {\n    [\n")
    for token, name in zip(tokens, names):
        out.append(f'      ("{token}", {name}),\n')
    out.append("    ]\n  }\n}\n\n")
    out.append("/// One theme: a light and a dark palette.\n")
    out.append("public struct Theme: Equatable, Sendable {\n")
    out.append("  public let id: ThemeID\n  public let light: ThemePalette\n")
    out.append("  public let dark: ThemePalette\n}\n\n")
    out.append("public enum ThemeCatalog {\n")
    out.append("  public static let all: [Theme] = [\n")
    for theme in data["themes"]:
        out.append(f'    Theme(id: .theme{theme["id"]}, light: light{theme["id"]}, '
                   f'dark: dark{theme["id"]}),\n')
    out.append("  ]\n\n")
    for theme in data["themes"]:
        for scheme in ("light", "dark"):
            out.append(f'  static let {scheme}{theme["id"]} = ThemePalette(\n')
            lines = [f"    {name}: ThemeColor({rgba(theme[scheme][token])})"
                     for token, name in zip(tokens, names)]
            out.append(",\n".join(lines) + "\n  )\n")
    out.append("}\n")
    return "".join(out)


def colors_source(data):
    names = [camel(token) for token in data["tokens"]]
    out = [HEADER, "// swift-format-ignore-file\n\nimport SwiftUI\n\n"]
    out.append("extension AppThemeColors {\n")
    for name in names:
        out.append(f"  public var {name}: Color {{ Color(palette.{name}) }}\n")
    out.append("}\n")
    return "".join(out)


def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path, encoding="utf-8") as handle:
            if handle.read() == text:
                return
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


def generate(json_path, folder):
    with open(json_path, encoding="utf-8") as handle:
        data = json.load(handle)
    validate(data)
    os.makedirs(folder, exist_ok=True)
    write_if_changed(os.path.join(folder, "ThemeCatalog.generated.swift"), catalog_source(data))
    write_if_changed(os.path.join(folder, "ThemeColors.generated.swift"), colors_source(data))


def self_test():
    problems = []
    for token, name in [("surface/background", "surfaceBackground"),
                        ("account/1/start", "account1Start"),
                        ("content/on-accent", "contentOnAccent"),
                        ("chart/2-tint", "chart2Tint"),
                        ("accent/tint-strong", "accentTintStrong")]:
        if camel(token) != name:
            problems.append(f"{token} -> {camel(token)}, expected {name}")
    if rgba("#fbf8f3") != "0xFBF8F3FF" or rgba("#ffffffe0") != "0xFFFFFFE0":
        problems.append("colour parsing")
    try:
        rgba("#fff")
        problems.append("a short colour was accepted")
    except ValueError:
        pass
    palette = {"surface/background": "#000000", "accent/tint": "#11223344"}
    data = {"tokens": list(palette),
            "themes": [{"id": "01", "light": palette, "dark": palette}]}
    validate(data)
    first = catalog_source(data) + colors_source(data)
    if first != catalog_source(data) + colors_source(data):
        problems.append("output is not deterministic")
    if "accentTint: ThemeColor(0x11223344)" not in first:
        problems.append("a token is missing from the output")
    broken = {"tokens": data["tokens"],
              "themes": [{"id": "01", "light": palette, "dark": {"surface/background": "#000000"}}]}
    try:
        validate(broken)
        problems.append("a palette missing a token was accepted")
    except ValueError:
        pass
    if problems:
        sys.exit("make_themes self-test: " + "; ".join(problems))
    print("make_themes self-test: ok")


def main(arguments):
    if arguments == ["--self-test"]:
        self_test()
    elif len(arguments) in (1, 2):
        generate(arguments[0], arguments[1] if len(arguments) == 2 else DEFAULT_DIR)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
